import { isTileTone, type IconStyle, type ToneStyle } from '../types'

function toneVars(tone: ToneStyle): string {
  const accent = tone.accent === undefined ? '' : `; --sg-accent: ${tone.accent}`
  return `--sg-line: ${tone.line}; --sg-plane: ${tone.plane}${accent}`
}

function background(bg: NonNullable<ToneStyle['bg']>): string {
  if (typeof bg === 'string') return bg
  return `linear-gradient(${bg.angle}deg, ${bg.stops.join(', ')})`
}

/** The tone sheet: role rules keyed off `--sg-*` vars, one class per tone, one tile class per tile tone. `scope` prefixes every rule so several styles coexist on one page. */
export function buildCss(style: IconStyle, opts?: { readonly scope?: string }): string {
  const p = opts?.scope === undefined ? '' : `${opts.scope} `
  const lines = [
    '/* Generated by sigil from icon.md — do not edit. */',
    `${p}.sg-svg { display: inline-block; vertical-align: middle; flex-shrink: 0 }`,
    `${p}.sg-svg .sg-plane { fill: var(--sg-plane); stroke: none }`,
    `${p}.sg-svg .sg-line { fill: none; stroke: var(--sg-line); stroke-width: ${style.stroke}; stroke-linecap: ${style.caps}; stroke-linejoin: ${style.joins} }`,
    `${p}.sg-svg .sg-dot { fill: var(--sg-line) }`,
    `${p}.sg-svg .sg-accent { fill: var(--sg-accent, var(--sg-line)) }`,
  ]
  const tones = Object.entries(style.tones)
  for (const [name, tone] of tones) lines.push(`${p}.sg-tone-${name} { ${toneVars(tone)} }`)
  for (const [name, tone] of tones) {
    if (!isTileTone(tone) || tone.bg === undefined) continue
    const shadow = tone.shadow === undefined ? '' : `; box-shadow: ${tone.shadow}`
    lines.push(
      `${p}.sg-tile-${name} { ${toneVars(tone)}; display: inline-grid; place-items: center; border-radius: ${tone.radius ?? '25%'}; background: ${background(tone.bg)}${shadow} }`,
    )
  }
  return `${lines.join('\n')}\n`
}
